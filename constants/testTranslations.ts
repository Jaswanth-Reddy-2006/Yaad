/**
 * Normalizes input text for resilient lookup:
 * - Trims whitespace
 * - Collapses multiple spaces
 * - Lowercases for Latin/English
 * - Strips common English and Indic punctuation marks (?, !, ., ,, ;, :, ।, ॥)
 */
export function normalizeText(text: string): string {
  if (!text) return '';
  return text
    .trim()
    .toLowerCase()
    .replace(/[?!.,;:।\u0964\u0965]/g, '')
    .replace(/\s+/g, ' ');
}

