export const NOT_FOUND_MESSAGE = 'Translation not available for this test phrase.';

/**
 * Translates Regional Language input to English using local dictionary.
 */
export function translateRegionalToEnglish(inputText: string, selectedLang: LanguageCode): string {
  const cleanInput = normalizeText(inputText);
  if (!cleanInput) return '';

  for (const item of PREDEFINED_TEST_PHRASES) {
    const regionalVariants = item.translations[selectedLang] || [];
    for (const variant of regionalVariants) {
      if (normalizeText(variant) === cleanInput) {
        return item.english;
      }
    }
  }

  return NOT_FOUND_MESSAGE;
}

/**
 * Translates English input to Current App Language using local dictionary.
 */
export function translateEnglishToAppLanguage(englishInput: string, appLang: LanguageCode): string {
  const cleanInput = normalizeText(englishInput);
  if (!cleanInput) return '';

  for (const item of PREDEFINED_TEST_PHRASES) {
    // Check if input matches standard English or English variants
    const enVariants = item.translations.en || [item.english];
    const matchesEn = enVariants.some((v) => normalizeText(v) === cleanInput);

    if (matchesEn) {
      const targetVariants = item.translations[appLang];
      if (targetVariants && targetVariants.length > 0) {
        return targetVariants[0]; // Primary idiomatic translation
      }
      return item.english;
    }
  }

  return NOT_FOUND_MESSAGE;
}
